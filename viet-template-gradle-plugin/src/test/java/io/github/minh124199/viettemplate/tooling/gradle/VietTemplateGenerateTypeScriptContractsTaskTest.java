package io.github.minh124199.viettemplate.tooling.gradle;

import static org.assertj.core.api.Assertions.assertThat;

import java.io.File;
import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.util.Arrays;
import java.util.List;
import java.util.stream.Collectors;
import org.gradle.testkit.runner.BuildResult;
import org.gradle.testkit.runner.GradleRunner;
import org.gradle.testkit.runner.TaskOutcome;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class VietTemplateGenerateTypeScriptContractsTaskTest {

  private static GradleRunner createRunner(Path projectDir) {
    GradleRunner runner = GradleRunner.create().withProjectDir(projectDir.toFile());
    if (VietTemplateGenerateTypeScriptContractsTaskTest.class
            .getClassLoader()
            .getResource("plugin-under-test-metadata.properties")
        != null) {
      return runner.withPluginClasspath();
    }
    List<File> cp =
        Arrays.stream(System.getProperty("java.class.path").split(File.pathSeparator))
            .map(File::new)
            .filter(File::exists)
            .collect(Collectors.toList());
    return runner.withGradleVersion("9.7.1").withPluginClasspath(cp);
  }

  @Test
  @DisplayName(
      "Generates deterministic TypeScript contract declarations (*.vtl.d.ts) via GradleRunner")
  void testGenerateTypeScriptContracts(@TempDir Path projectDir) throws Exception {
    Files.writeString(
        projectDir.resolve("settings.gradle.kts"),
        "rootProject.name = \"test-ts-contracts-project\"\n",
        StandardCharsets.UTF_8);

    Files.writeString(
        projectDir.resolve("build.gradle.kts"),
        "plugins {\n"
            + "    java\n"
            + "    id(\"io.github.minh124199.viet-template\")\n"
            + "}\n"
            + "repositories {\n"
            + "    mavenCentral()\n"
            + "}\n",
        StandardCharsets.UTF_8);

    Path templateDir = projectDir.resolve("src/main/viet-template");
    Files.createDirectories(templateDir.resolve("orders"));
    Files.writeString(
        templateDir.resolve("orders/detail.vtl"),
        """
        #param(String $customer)
        #param(long $orderId)
        <div>Order #$orderId for $customer</div>
        """,
        StandardCharsets.UTF_8);

    BuildResult result =
        createRunner(projectDir)
            .withArguments(VietTemplatePlugin.GENERATE_TYPESCRIPT_CONTRACTS_TASK_NAME)
            .build();

    assertThat(result.task(":" + VietTemplatePlugin.GENERATE_TYPESCRIPT_CONTRACTS_TASK_NAME))
        .isNotNull();
    assertThat(
            result
                .task(":" + VietTemplatePlugin.GENERATE_TYPESCRIPT_CONTRACTS_TASK_NAME)
                .getOutcome())
        .isEqualTo(TaskOutcome.SUCCESS);

    Path dtsFile =
        projectDir.resolve("build/generated/viet-template/typescript/orders/detail.vtl.d.ts");
    assertThat(dtsFile).isRegularFile();
    String dts = Files.readString(dtsFile, StandardCharsets.UTF_8);
    assertThat(dts).contains("// Generated by Viet Template M46.");
    assertThat(dts).contains("export interface OrdersDetailTemplateParameters {");
    assertThat(dts).contains("customer: string;");
    assertThat(dts).contains("orderId: number;");

    // Manifest check
    Path manifest =
        projectDir.resolve(
            "build/generated/viet-template/typescript/.viet-template-typescript-manifest.json");
    assertThat(manifest).isRegularFile();
  }

  @Test
  @DisplayName("Gradle task up-to-date check when inputs are unchanged")
  void testUpToDateOnSecondRun(@TempDir Path projectDir) throws Exception {
    Files.writeString(
        projectDir.resolve("settings.gradle.kts"),
        "rootProject.name = \"test-uptodate-project\"\n",
        StandardCharsets.UTF_8);

    Files.writeString(
        projectDir.resolve("build.gradle.kts"),
        "plugins {\n"
            + "    java\n"
            + "    id(\"io.github.minh124199.viet-template\")\n"
            + "}\n"
            + "repositories {\n"
            + "    mavenCentral()\n"
            + "}\n",
        StandardCharsets.UTF_8);

    Path templateDir = projectDir.resolve("src/main/viet-template");
    Files.createDirectories(templateDir);
    Files.writeString(
        templateDir.resolve("index.vtl"),
        "#param(String $title)\n<h1>$title</h1>",
        StandardCharsets.UTF_8);

    BuildResult firstRun =
        createRunner(projectDir)
            .withArguments(VietTemplatePlugin.GENERATE_TYPESCRIPT_CONTRACTS_TASK_NAME)
            .build();
    assertThat(
            firstRun
                .task(":" + VietTemplatePlugin.GENERATE_TYPESCRIPT_CONTRACTS_TASK_NAME)
                .getOutcome())
        .isEqualTo(TaskOutcome.SUCCESS);

    BuildResult secondRun =
        createRunner(projectDir)
            .withArguments(VietTemplatePlugin.GENERATE_TYPESCRIPT_CONTRACTS_TASK_NAME)
            .build();
    assertThat(
            secondRun
                .task(":" + VietTemplatePlugin.GENERATE_TYPESCRIPT_CONTRACTS_TASK_NAME)
                .getOutcome())
        .isEqualTo(TaskOutcome.UP_TO_DATE);
  }

  @Test
  @DisplayName("Safe stale output cleanup preserves foreign files in output directory")
  void testSafeStaleCleanup(@TempDir Path projectDir) throws Exception {
    Files.writeString(
        projectDir.resolve("settings.gradle.kts"),
        "rootProject.name = \"test-stale-cleanup-project\"\n",
        StandardCharsets.UTF_8);

    Files.writeString(
        projectDir.resolve("build.gradle.kts"),
        "plugins {\n"
            + "    java\n"
            + "    id(\"io.github.minh124199.viet-template\")\n"
            + "}\n"
            + "repositories {\n"
            + "    mavenCentral()\n"
            + "}\n",
        StandardCharsets.UTF_8);

    Path templateDir = projectDir.resolve("src/main/viet-template");
    Files.createDirectories(templateDir);
    Path tpl1 = templateDir.resolve("item1.vtl");
    Path tpl2 = templateDir.resolve("item2.vtl");
    Files.writeString(tpl1, "#param(String $a)\n$a", StandardCharsets.UTF_8);
    Files.writeString(tpl2, "#param(String $b)\n$b", StandardCharsets.UTF_8);

    createRunner(projectDir)
        .withArguments(VietTemplatePlugin.GENERATE_TYPESCRIPT_CONTRACTS_TASK_NAME)
        .build();

    Path outDir = projectDir.resolve("build/generated/viet-template/typescript");
    Path dts1 = outDir.resolve("item1.vtl.d.ts");
    Path dts2 = outDir.resolve("item2.vtl.d.ts");
    assertThat(dts1).isRegularFile();
    assertThat(dts2).isRegularFile();

    // Create foreign file in output dir
    Path foreignFile = outDir.resolve("foreign.d.ts");
    Files.writeString(foreignFile, "export interface Foreign {}", StandardCharsets.UTF_8);

    // Remove tpl2
    Files.delete(tpl2);

    createRunner(projectDir)
        .withArguments(VietTemplatePlugin.GENERATE_TYPESCRIPT_CONTRACTS_TASK_NAME)
        .build();

    assertThat(dts1).isRegularFile();
    assertThat(dts2).doesNotExist(); // Owned stale file cleaned up
    assertThat(foreignFile).isRegularFile(); // Foreign unowned file preserved
  }
}
