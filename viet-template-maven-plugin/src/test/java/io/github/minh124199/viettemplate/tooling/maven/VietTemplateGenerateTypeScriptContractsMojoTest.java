package io.github.minh124199.viettemplate.tooling.maven;

import static org.assertj.core.api.Assertions.assertThat;
import static org.assertj.core.api.Assertions.assertThatCode;

import java.nio.charset.StandardCharsets;
import java.nio.file.Files;
import java.nio.file.Path;
import java.nio.file.attribute.FileTime;
import java.time.Instant;
import org.junit.jupiter.api.DisplayName;
import org.junit.jupiter.api.Test;
import org.junit.jupiter.api.io.TempDir;

class VietTemplateGenerateTypeScriptContractsMojoTest {

  @Test
  @DisplayName("Generates TypeScript contract declarations (*.vtl.d.ts) from templates with #param")
  void testGenerateContractsFromTemplate(@TempDir Path tempDir) throws Exception {
    Path srcDir = tempDir.resolve("src/main/viet-template");
    Path tsOutputDir = tempDir.resolve("target/generated-sources/viet-template/typescript");
    Files.createDirectories(srcDir.resolve("users"));

    String templateContent =
        """
        #param(String $username)
        #param(long $userId)
        #param(boolean $active)
        <div>User: $username (ID: $userId, Active: $active)</div>
        """;
    Files.writeString(srcDir.resolve("users/profile.vtl"), templateContent, StandardCharsets.UTF_8);

    VietTemplateGenerateTypeScriptContractsMojo mojo =
        new VietTemplateGenerateTypeScriptContractsMojo();
    mojo.setSourceDirectory(srcDir.toFile());
    mojo.setTypeScriptOutputDirectory(tsOutputDir.toFile());

    assertThatCode(mojo::execute).doesNotThrowAnyException();

    Path dtsFile = tsOutputDir.resolve("users/profile.vtl.d.ts");
    assertThat(dtsFile).isRegularFile();
    String content = Files.readString(dtsFile, StandardCharsets.UTF_8);
    assertThat(content).contains("// Generated by Viet Template M46.");
    assertThat(content).contains("export interface UsersProfileTemplateParameters {");
    assertThat(content).contains("username: string;");
    assertThat(content).contains("userId: number;");
    assertThat(content).contains("active: boolean;");

    // Manifest should exist
    Path manifest = tsOutputDir.resolve(".viet-template-typescript-manifest.json");
    assertThat(manifest).isRegularFile();
    String manifestContent = Files.readString(manifest, StandardCharsets.UTF_8);
    assertThat(manifestContent).contains("users/profile.vtl.d.ts");
  }

  @Test
  @DisplayName("Incremental write avoidance: preserves mtime when content is unchanged")
  void testIncrementalWriteAvoidance(@TempDir Path tempDir) throws Exception {
    Path srcDir = tempDir.resolve("src/main/viet-template");
    Path tsOutputDir = tempDir.resolve("target/generated-sources/viet-template/typescript");
    Files.createDirectories(srcDir);

    Files.writeString(
        srcDir.resolve("index.vtl"),
        "#param(String $title)\n<h1>$title</h1>",
        StandardCharsets.UTF_8);

    VietTemplateGenerateTypeScriptContractsMojo mojo =
        new VietTemplateGenerateTypeScriptContractsMojo();
    mojo.setSourceDirectory(srcDir.toFile());
    mojo.setTypeScriptOutputDirectory(tsOutputDir.toFile());

    mojo.execute();

    Path dtsFile = tsOutputDir.resolve("index.vtl.d.ts");
    assertThat(dtsFile).isRegularFile();

    FileTime artificialTime = FileTime.from(Instant.parse("2024-01-01T00:00:00Z"));
    Files.setLastModifiedTime(dtsFile, artificialTime);

    // Second execution with identical inputs
    mojo.execute();

    assertThat(Files.getLastModifiedTime(dtsFile)).isEqualTo(artificialTime);
  }

  @Test
  @DisplayName(
      "Safe stale output cleanup: deletes owned stale files but leaves foreign files untouched")
  void testSafeStaleCleanup(@TempDir Path tempDir) throws Exception {
    Path srcDir = tempDir.resolve("src/main/viet-template");
    Path tsOutputDir = tempDir.resolve("target/generated-sources/viet-template/typescript");
    Files.createDirectories(srcDir);

    Path templateA = srcDir.resolve("viewA.vtl");
    Path templateB = srcDir.resolve("viewB.vtl");
    Files.writeString(templateA, "#param(String $a)\n$a", StandardCharsets.UTF_8);
    Files.writeString(templateB, "#param(String $b)\n$b", StandardCharsets.UTF_8);

    VietTemplateGenerateTypeScriptContractsMojo mojo =
        new VietTemplateGenerateTypeScriptContractsMojo();
    mojo.setSourceDirectory(srcDir.toFile());
    mojo.setTypeScriptOutputDirectory(tsOutputDir.toFile());
    mojo.setCleanStaleOutputs(true);

    mojo.execute();

    Path dtsA = tsOutputDir.resolve("viewA.vtl.d.ts");
    Path dtsB = tsOutputDir.resolve("viewB.vtl.d.ts");
    assertThat(dtsA).isRegularFile();
    assertThat(dtsB).isRegularFile();

    // Create a foreign file in output directory
    Path foreignFile = tsOutputDir.resolve("foreign.d.ts");
    Files.writeString(foreignFile, "export interface Foreign {}", StandardCharsets.UTF_8);

    // Delete templateB
    Files.delete(templateB);

    // Re-run
    mojo.execute();

    assertThat(dtsA).isRegularFile();
    assertThat(dtsB).doesNotExist(); // Owned stale file deleted
    assertThat(foreignFile).isRegularFile(); // Foreign unowned file preserved!
  }

  @Test
  @DisplayName("Skips execution when skip=true")
  void testSkipFlag(@TempDir Path tempDir) throws Exception {
    Path srcDir = tempDir.resolve("src/main/viet-template");
    Path tsOutputDir = tempDir.resolve("target/generated-sources/viet-template/typescript");
    Files.createDirectories(srcDir);
    Files.writeString(srcDir.resolve("test.vtl"), "#param(String $s)\n$s", StandardCharsets.UTF_8);

    VietTemplateGenerateTypeScriptContractsMojo mojo =
        new VietTemplateGenerateTypeScriptContractsMojo();
    mojo.setSourceDirectory(srcDir.toFile());
    mojo.setTypeScriptOutputDirectory(tsOutputDir.toFile());
    mojo.setSkip(true);

    assertThatCode(mojo::execute).doesNotThrowAnyException();
    assertThat(tsOutputDir).doesNotExist();
  }

  @Test
  @DisplayName("Skips gracefully when sourceDirectory does not exist")
  void testNonExistentSourceDirectory(@TempDir Path tempDir) {
    Path srcDir = tempDir.resolve("non-existent");
    Path tsOutputDir = tempDir.resolve("target/generated-sources/viet-template/typescript");

    VietTemplateGenerateTypeScriptContractsMojo mojo =
        new VietTemplateGenerateTypeScriptContractsMojo();
    mojo.setSourceDirectory(srcDir.toFile());
    mojo.setTypeScriptOutputDirectory(tsOutputDir.toFile());

    assertThatCode(mojo::execute).doesNotThrowAnyException();
    assertThat(tsOutputDir).doesNotExist();
  }
}
