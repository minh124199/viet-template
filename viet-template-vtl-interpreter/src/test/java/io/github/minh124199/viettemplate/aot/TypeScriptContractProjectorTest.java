class TypeScriptContractProjectorTest {

  public record UserRecord(String name, long id, boolean active) {}

  public record DepartmentRecord(String deptName, List<UserRecord> members) {}

  public record RecursiveItem(String name, List<RecursiveItem> children) {}

  @Test
  @DisplayName("Candidate D: projects TemplateContract into deterministic TypeScript declaration")
  void testProjectContract() {
    TypeScriptContractProjector projector = TypeScriptContractProjector.create();

    TemplateContract contract =
        TemplateContract.builder(TemplateId.of("views/user-card.vtl"))
            .parameter(TemplateParameter.of("user", TemplateType.of(UserRecord.class)))
            .parameter(TemplateParameter.of("dept", TemplateType.of(DepartmentRecord.class), true))
            .build();

    String dts = projector.projectContract(contract);

    assertThat(dts).contains("// Generated by Viet Template M46.");
    assertThat(dts).contains("export interface TypeScriptContractProjectorTest_UserRecord {");
    assertThat(dts).contains("  active: boolean;");
    assertThat(dts).contains("  id: number;");
    assertThat(dts).contains("  name: string | null;");
    assertThat(dts).contains("export interface TypeScriptContractProjectorTest_DepartmentRecord {");
    assertThat(dts).contains("  deptName: string | null;");
    assertThat(dts).contains("  members: TypeScriptContractProjectorTest_UserRecord[] | null;");
    assertThat(dts).contains("export interface ViewsUserCardTemplateParameters {");
    assertThat(dts).contains("  dept: TypeScriptContractProjectorTest_DepartmentRecord | null;");
    assertThat(dts).contains("  user: TypeScriptContractProjectorTest_UserRecord | null;");
    assertThat(dts)
        .contains("export interface TemplateParameters extends ViewsUserCardTemplateParameters {}");
  }

  @Test
  @DisplayName("Batch template projection with inline #param and manifest output")
  void testProjectTemplatesBatch(@TempDir Path tempDir) throws Exception {
    Path srcDir = tempDir.resolve("templates");
    Path outDir = tempDir.resolve("out");
    Files.createDirectories(srcDir.resolve("reports"));

    Files.writeString(
        srcDir.resolve("reports/summary.vtl"),
        """
        #param(String $title)
        #param(int $year)
        <h1>$title - $year</h1>
        """,
        StandardCharsets.UTF_8);

    TypeScriptContractProjector projector = TypeScriptContractProjector.create();
    Map<String, Integer> summary =
        projector.projectTemplates(
            srcDir,
            outDir,
            List.of("**/*.vtl"),
            List.of(),
            StandardCharsets.UTF_8,
            getClass().getClassLoader(),
            true);

    assertThat(summary.get("generated")).isEqualTo(1);
    assertThat(summary.get("written")).isEqualTo(1);
    assertThat(summary.get("skipped")).isEqualTo(0);
    assertThat(summary.get("deleted")).isEqualTo(0);

    Path dtsFile = outDir.resolve("reports/summary.vtl.d.ts");
    assertThat(dtsFile).isRegularFile();
    String content = Files.readString(dtsFile, StandardCharsets.UTF_8);
    assertThat(content).contains("export interface ReportsSummaryTemplateParameters {");
    assertThat(content).contains("  title: string;");
    assertThat(content).contains("  year: number;");

    Path manifestFile = outDir.resolve(".viet-template-typescript-manifest.json");
    assertThat(manifestFile).isRegularFile();
    String manifestContent = Files.readString(manifestFile, StandardCharsets.UTF_8);
    assertThat(manifestContent).contains("reports/summary.vtl.d.ts");
  }

  @Test
  @DisplayName("writeIfChanged preserves mtime when content is identical")
  void testWriteIfChangedPreservesMtime(@TempDir Path tempDir) throws Exception {
    Path targetFile = tempDir.resolve("sample.d.ts");
    String initialContent = "export interface Sample { id: number; }\n";

    boolean firstWrite = TypeScriptContractProjector.writeIfChanged(targetFile, initialContent);
    assertThat(firstWrite).isTrue();
    assertThat(targetFile).isRegularFile();

    FileTime artificialTime = FileTime.from(Instant.parse("2023-01-01T12:00:00Z"));
    Files.setLastModifiedTime(targetFile, artificialTime);

    boolean secondWrite = TypeScriptContractProjector.writeIfChanged(targetFile, initialContent);
    assertThat(secondWrite).isFalse();
    assertThat(Files.getLastModifiedTime(targetFile)).isEqualTo(artificialTime);

    boolean thirdWrite =
        TypeScriptContractProjector.writeIfChanged(
            targetFile, "export interface Sample { id: string; }\n");
    assertThat(thirdWrite).isTrue();
    assertThat(Files.getLastModifiedTime(targetFile)).isNotEqualTo(artificialTime);
  }

  @Test
  @DisplayName(
      "Safe stale output cleanup strictly deletes owned outputs and protects foreign files")
  void testSafeStaleCleanup(@TempDir Path tempDir) throws Exception {
    Path outDir = tempDir.resolve("output");
    Files.createDirectories(outDir);

    Path ownedA = outDir.resolve("viewA.vtl.d.ts");
    Path ownedB = outDir.resolve("viewB.vtl.d.ts");
    Path foreignFile = outDir.resolve("foreign.d.ts");

    Files.writeString(ownedA, "// owned A", StandardCharsets.UTF_8);
    Files.writeString(ownedB, "// owned B", StandardCharsets.UTF_8);
    Files.writeString(foreignFile, "// foreign file", StandardCharsets.UTF_8);

    Set<Path> previousOwned = Set.of(ownedA, ownedB);
    Set<Path> currentOutputs = Set.of(ownedA); // ownedB is now stale

    int deleted =
        TypeScriptContractProjector.cleanStaleOutputs(outDir, currentOutputs, previousOwned);

    assertThat(deleted).isEqualTo(1);
    assertThat(ownedA).isRegularFile();
    assertThat(ownedB).doesNotExist();
    assertThat(foreignFile).isRegularFile();
  }

  @Test
  @DisplayName("Security: path traversal and absolute escapes are rejected")
  void testPathTraversalRejected(@TempDir Path tempDir) {
    Path outDir = tempDir.resolve("output");

    assertThatThrownBy(
            () ->
                TypeScriptContractProjector.deriveDeclarationFilePath(
                    outDir, "../../etc/passwd.vtl"))
        .isInstanceOf(IllegalArgumentException.class)
        .hasMessageContaining("Path traversal detected");

    assertThatThrownBy(
            () ->
                TypeScriptContractProjector.deriveDeclarationFilePath(
                    outDir, "sub/../../outside/hack.vtl"))
        .isInstanceOf(IllegalArgumentException.class)
        .hasMessageContaining("Path traversal detected");

    assertThatThrownBy(
            () ->
                TypeScriptContractProjector.deriveDeclarationFilePath(outDir, "/absolute/path.vtl"))
        .isInstanceOf(IllegalArgumentException.class)
        .hasMessageContaining("Path traversal detected");

    assertThatThrownBy(
            () ->
                TypeScriptContractProjector.deriveDeclarationFilePath(
                    outDir, "C:\\outside\\evil.vtl"))
        .isInstanceOf(IllegalArgumentException.class)
        .hasMessageContaining("Path traversal detected");

    assertThatThrownBy(
            () ->
                TypeScriptContractProjector.deriveDeclarationFilePath(
                    outDir, "\\windows\\system32\\evil.vtl"))
        .isInstanceOf(IllegalArgumentException.class)
        .hasMessageContaining("Path traversal detected");

    assertThatThrownBy(
            () ->
                TypeScriptContractProjector.deriveDeclarationFilePath(
                    outDir, "sub\\..\\..\\outside.vtl"))
        .isInstanceOf(IllegalArgumentException.class)
        .hasMessageContaining("Path traversal detected");

    assertThatThrownBy(
            () -> TypeScriptContractProjector.deriveDeclarationFilePath(outDir, "%2e%2e/evil.vtl"))
        .isInstanceOf(IllegalArgumentException.class)
        .hasMessageContaining("Path traversal detected");
  }

  @Test
  @DisplayName(
      "Security: MemberAccessPolicy exclusions prevent getClass, ClassLoader, Thread projection")
  void testMemberAccessPolicyEnforced() {
    TypeScriptContractProjector projector =
        TypeScriptContractProjector.create(MemberAccessPolicy.standard());

    String dts = projector.projectClass(UserRecord.class, "user.vtl");
    assertThat(dts).doesNotContain("getClass");
    assertThat(dts).doesNotContain("classLoader");
    assertThat(dts).doesNotContain("declaringClass");
  }

  @Test
  @DisplayName("Recursive types project safely without cycle or overflow")
  void testRecursiveTypeProjection() {
    TypeScriptContractProjector projector = TypeScriptContractProjector.create();

    TemplateContract contract =
        TemplateContract.builder(TemplateId.of("tree.vtl"))
            .parameter(TemplateParameter.of("root", TemplateType.of(RecursiveItem.class)))
            .build();

    String dts = projector.projectContract(contract);
    assertThat(dts).contains("export interface TypeScriptContractProjectorTest_RecursiveItem {");
    assertThat(dts).contains("  children: TypeScriptContractProjectorTest_RecursiveItem[] | null;");
    assertThat(dts).contains("  name: string | null;");
  }

  @Test
  @DisplayName("Disambiguation across packages deterministically creates unique names")
  void testCollisionDisambiguation() {
    Set<String> fqcns =
        Set.of("com.example.billing.Invoice", "com.example.shipping.Invoice", "org.other.Invoice");

    Map<String, String> resolved = TypeScriptContractProjector.resolveTypeNames(fqcns);

    assertThat(resolved.values()).doesNotHaveDuplicates();
    assertThat(resolved.get("com.example.billing.Invoice")).isEqualTo("Billing_Invoice");
    assertThat(resolved.get("com.example.shipping.Invoice")).isEqualTo("Shipping_Invoice");
    assertThat(resolved.get("org.other.Invoice")).isEqualTo("Other_Invoice");
  }

  @Test
  @DisplayName("Security: manifest tampering attempting to target external files is blocked")
  void testManifestTamperingRejected(@TempDir Path tempDir) throws Exception {
    Path outDir = tempDir.resolve("out");
    Files.createDirectories(outDir);

    Path victimFile = tempDir.resolve("victim.vtl.d.ts");
    Files.writeString(victimFile, "// victim file outside output dir", StandardCharsets.UTF_8);

    // Write a tampered manifest pointing outside outDir
    String tamperedManifest =
        """
        {
          "schemaVersion": 1,
          "files": {
            "external.vtl": {
              "output": "../victim.vtl.d.ts",
              "fingerprint": "abc"
            }
          }
        }
        """;
    Files.writeString(
        outDir.resolve(".viet-template-typescript-manifest.json"),
        tamperedManifest,
        StandardCharsets.UTF_8);

    Path dummyTemplateDir = tempDir.resolve("templates");
    Files.createDirectories(dummyTemplateDir);

    TypeScriptContractProjector projector = TypeScriptContractProjector.create();
    projector.projectTemplates(
        dummyTemplateDir,
        outDir,
        List.of("**/*.vtl"),
        List.of(),
        StandardCharsets.UTF_8,
        getClass().getClassLoader(),
        true);

    // Victim file must NOT be deleted
    assertThat(victimFile).isRegularFile();
  }

  @Test
  @DisplayName("Security: symlinked directories escaping output root are protected from deletion")
  void testSymlinkEscapePrevention(@TempDir Path tempDir) throws Exception {
    Path outDir = tempDir.resolve("out");
    Path externalDir = tempDir.resolve("external-sensitive");
    Files.createDirectories(outDir);
    Files.createDirectories(externalDir);

    Path externalFile = externalDir.resolve("sensitive.vtl.d.ts");
    Files.writeString(externalFile, "// do not delete me", StandardCharsets.UTF_8);

    // Create a symlink inside outDir pointing to externalDir
    Path symlinkDir = outDir.resolve("symlinked-dir");
    try {
      Files.createSymbolicLink(symlinkDir, externalDir);
    } catch (UnsupportedOperationException | IOException e) {
      // If filesystem does not support symlinks, skip symlink creation check
      return;
    }

    Set<Path> previousOwned = Set.of(symlinkDir.resolve("sensitive.vtl.d.ts"));
    Set<Path> currentOutputs = Set.of();

    int deleted =
        TypeScriptContractProjector.cleanStaleOutputs(outDir, currentOutputs, previousOwned);

    assertThat(deleted).isEqualTo(0);
    assertThat(externalFile).isRegularFile(); // External sensitive file strictly protected
  }

  @Test
  @DisplayName(
      "Robustness: unusual template names with spaces and symbols produce valid TypeScript"
          + " identifiers")
  void testUnusualTemplateNamesSanitization() {
    assertThat(TypeScriptContractProjector.deriveTemplateParametersName("users/my profile.vtl"))
        .isEqualTo("UsersMyProfileTemplateParameters");

    assertThat(TypeScriptContractProjector.deriveTemplateParametersName("123/items.vtl"))
        .matches("^[a-zA-Z_$][a-zA-Z0-9_$]*$");

    assertThat(TypeScriptContractProjector.deriveTemplateParametersName("special!@#$/test.vtl"))
        .matches("^[a-zA-Z_$][a-zA-Z0-9_$]*$");

    assertThat(TypeScriptContractProjector.deriveTemplateParametersName("default/export.vtl"))
        .matches("^[a-zA-Z_$][a-zA-Z0-9_$]*$");

    assertThat(TypeScriptContractProjector.deriveTemplateParametersName(null))
        .isEqualTo("TemplateParameters");
    assertThat(TypeScriptContractProjector.deriveTemplateParametersName(""))
        .isEqualTo("TemplateParameters");
  }
}
